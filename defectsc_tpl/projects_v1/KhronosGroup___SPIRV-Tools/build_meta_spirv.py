def _load_fmt_builder():
    path = PROJECT_DIR.parent / "fmtlib___fmt" / "build_meta_fmt.py"
    spec = importlib.util.spec_from_file_location("_spirv_fmt_metadata_base", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load shared metadata builder: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


