def acquire_lock(out_root: Path):
    key = hashlib.md5(str(out_root.resolve()).encode("utf-8")).hexdigest()
    path = Path("/tmp") / f".build_meta_spirv.{key}.lock"
    fp = path.open("a+", encoding="utf-8")
    try:
        fcntl.flock(fp.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        fp.close()
        raise RuntimeError(f"Another SPIRV metadata process is using {out_root}")
    fp.seek(0)
    fp.truncate(0)
    fp.write(f"pid={os.getpid()} started={time.strftime('%Y-%m-%d %H:%M:%S')}\n")
    fp.flush()
    return fp


def git_checkout(repo: Path, sha: str, label: str) -> None:
    """Reset sources while preserving dependencies and the incremental build."""
    log(f"  [git] checkout {label}={sha[:10]}")
    base.run(["git", "reset", "--hard"], cwd=repo, check=True)
    base.run(
        ["git", "clean", "-ffdx", "-e", "external/", "-e", f"{BUILD_DIR_NAME}/"],
        cwd=repo,
        check=True,
    )
    rc, _, _ = base.run(["git", "cat-file", "-e", f"{sha}^{{commit}}"], cwd=repo)
    if rc != 0:
        base.run(["git", "fetch", "--all", "--tags"], cwd=repo, check=True, timeout=1200)
    base.run(["git", "checkout", "--force", sha], cwd=repo, check=True)


base._git_checkout = git_checkout


def ensure_dependencies(repo: Path) -> bool:
    """Fetch the dependency revisions declared by the checked-out DEPS file."""
    marker = repo / "external/.build_meta_spirv_deps_ready"
    rc, head, _ = base.run(["git", "rev-parse", "HEAD"], cwd=repo)
    revision = head.strip() if rc == 0 else "unknown"
    required = [
        repo / "external/spirv-headers",
        repo / "external/googletest",
        repo / "external/effcee",
    ]
    if marker.is_file() and marker.read_text(errors="ignore").strip() == revision and all(p.is_dir() for p in required):
        return True

    sync_script = repo / "utils/git-sync-deps"
    if not sync_script.is_file():
        log("  [deps] missing utils/git-sync-deps; refusing unpinned dependency clones")
        return False
    log("  [deps] syncing revision-pinned dependencies")
    rc, out, err = base.run([sys.executable, str(sync_script)], cwd=repo, timeout=1800)
    if rc != 0:
        log(f"  [deps] sync FAILED rc={rc}\n{(out + err)[-3000:]}")
        return False
    if not all(p.is_dir() for p in required):
        missing = ", ".join(str(p.relative_to(repo)) for p in required if not p.is_dir())
        log(f"  [deps] sync completed but required directories are missing: {missing}")
        return False
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text(revision + "\n", encoding="utf-8")
    return True


def target_names(bug: BugEntry) -> List[str]:
    names = [str(item).strip() for item in bug.test_flags if str(item).strip()]
    return list(dict.fromkeys(names or ["spirv-tools-test_opt"]))


def ninja_target_names(ctest_targets: Sequence[str]) -> List[str]:
    """Map SPIRV's public CTest names to their underlying CMake targets."""
    targets = []
    for name in ctest_targets:
        target = name[len("spirv-tools-"):] if name.startswith("spirv-tools-") else name
        if target and target not in targets:
            targets.append(target)
    return targets


def compile_project(
    repo: Path,
    *,
    jobs: int,
    coverage: bool,
    targets: Sequence[str],
    build_all: bool,
    timeout: int = 2400,
) -> bool:
    if not ensure_dependencies(repo):
        return False

    build_dir = repo / BUILD_DIR_NAME
    build_dir.mkdir(parents=True, exist_ok=True)

    flags = COV_CFLAGS if coverage else BASE_CFLAGS
    if coverage:
        signal_header = base.write_gcov_signal_header(repo)
        flags += f" -include {shlex.quote(str(signal_header))}"
    ldflags = COV_LDFLAGS if coverage else ""
    cmake_args = [
        "cmake", "-G", "Ninja", "-S", str(repo), "-B", str(build_dir),
        "-DCMAKE_BUILD_TYPE=Debug",
        "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
        "-DSPIRV_WERROR=OFF",
        "-DSPIRV_SKIP_TESTS=OFF",
        "-DEFFCEE_BUILD_TESTING=OFF",
        "-DCMAKE_C_FLAGS=" + flags,
        "-DCMAKE_CXX_FLAGS=" + flags,
        "-DCMAKE_EXE_LINKER_FLAGS=" + ldflags,
        "-DCMAKE_SHARED_LINKER_FLAGS=" + ldflags,
    ]
    if shutil.which("ccache"):
        cmake_args.extend([
            "-DCMAKE_C_COMPILER_LAUNCHER=ccache",
            "-DCMAKE_CXX_COMPILER_LAUNCHER=ccache",
        ])
    phase = "GCOV" if coverage else "plain"
    log(f"  [build-{phase}] cmake configure")
    rc, out, err = base.run(cmake_args, cwd=repo, timeout=600)
    if rc != 0:
        log(f"  [build-{phase}] configure FAILED rc={rc}\n{(out + err)[-3000:]}")
        return False

    build_targets = ninja_target_names(targets)
    command = ["ninja", "-C", str(build_dir), f"-j{max(1, jobs)}"]
    if not build_all:
        command.extend(build_targets)
    log(f"  [build-{phase}] {' '.join(build_targets) if not build_all else 'default target'}")
    rc, out, err = base.run(command, cwd=repo, timeout=timeout)
    if rc != 0:
        log(f"  [build-{phase}] ninja FAILED rc={rc}\n{(out + err)[-3000:]}")
        return False
    if coverage and not list(build_dir.rglob("*.gcno")):
        log("  [build-GCOV] WARNING: no *.gcno files found")
    return True


GTEST_MACROS = ("TEST", "TEST_F", "TEST_P", "TYPED_TEST", "TYPED_TEST_P")
_GTEST_MACRO_RE = re.compile(r"\b(" + "|".join(GTEST_MACROS) + r")\s*\(")


def _matching(text: str, start: int, opening: str, closing: str) -> int:
    depth = 0
    quote = ""
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in ('"', "'"):
            quote = char
        elif char == opening:
            depth += 1
        elif char == closing:
            depth -= 1
            if depth == 0:
                return index
    return -1


def _split_args(text: str) -> List[str]:
    args: List[str] = []
    start = 0
    depths = {"(": 0, "[": 0, "{": 0, "<": 0}
    pairs = {")": "(", "]": "[", "}": "{", ">": "<"}
    for index, char in enumerate(text):
        if char in depths:
            depths[char] += 1
        elif char in pairs and depths[pairs[char]]:
            depths[pairs[char]] -= 1
        elif char == "," and not any(depths.values()):
            args.append(text[start:index].strip())
            start = index + 1
    args.append(text[start:].strip())
    return args


def gtest_blocks(source: str) -> List[dict]:
    blocks: List[dict] = []
    for match in _GTEST_MACRO_RE.finditer(source):
        open_paren = source.find("(", match.start())
        close_paren = _matching(source, open_paren, "(", ")")
        if close_paren < 0:
            continue
        args = _split_args(source[open_paren + 1:close_paren])
        if len(args) < 2:
            continue
        open_brace = source.find("{", close_paren)
        close_brace = _matching(source, open_brace, "{", "}") if open_brace >= 0 else close_paren
        end = close_brace + 1 if close_brace >= 0 else close_paren + 1
        blocks.append({
            "name": f"{args[0].strip()}.{args[1].strip()}",
            "macro": match.group(1),
            "suite": args[0].strip(),
            "line_start": source.count("\n", 0, match.start()) + 1,
            "line_end": source.count("\n", 0, end) + 1,
        })
    return blocks


def _changed_new_lines(diff: str) -> Dict[str, Set[int]]:
    changed: Dict[str, Set[int]] = {}
    current = ""
    line_no = 0
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            current = line[6:].strip()
            changed.setdefault(current, set())
            continue
        hunk = re.match(r"@@\s+-\d+(?:,\d+)?\s+\+(?P<start>\d+)(?:,\d+)?\s+@@", line)
        if hunk:
            line_no = int(hunk.group("start"))
            continue
        if not current or not line_no:
            continue
        if line.startswith("+") and not line.startswith("+++"):
            changed[current].add(line_no)
            line_no += 1
        elif line.startswith("-") and not line.startswith("---"):
            # A deletion has no new-side line of its own.  Mark its insertion
            # point so deletion-only changes still select the enclosing test.
            changed[current].add(line_no)
            continue
        else:
            line_no += 1
    return changed


_GTEST_INSTANTIATE_RE = re.compile(r"\bINSTANTIATE_TEST_(?:SUITE|CASE)_P\s*\(")


def gtest_instantiation_blocks(source: str) -> List[dict]:
    """Return parameterized-suite instantiation ranges and base suite names."""
    blocks: List[dict] = []
    for match in _GTEST_INSTANTIATE_RE.finditer(source):
        open_paren = source.find("(", match.start())
        close_paren = _matching(source, open_paren, "(", ")")
        if close_paren < 0:
            continue
        args = _split_args(source[open_paren + 1:close_paren])
        if len(args) < 2:
            continue
        blocks.append({
            "suite": args[1].strip(),
            "line_start": source.count("\n", 0, match.start()) + 1,
            "line_end": source.count("\n", 0, close_paren + 1) + 1,
        })
    return blocks


def regression_case_names(repo: Path, bug: BugEntry) -> Set[str]:
    if not bug.test_files or not bug.sha_before or not bug.sha_after:
        return set()
    rc, diff, _ = base.run(
        ["git", "diff", "--unified=0", bug.sha_before, bug.sha_after, "--", *bug.test_files],
        cwd=repo,
    )
    changed = _changed_new_lines(diff) if rc == 0 else {}
    names: Set[str] = set()
    for test_file in bug.test_files:
        rc_show, source, _ = base.run(["git", "show", f"{bug.sha_after}:{test_file}"], cwd=repo)
        if rc_show != 0:
            continue
        file_changes = changed.get(test_file, set())
        test_blocks = gtest_blocks(source)
        for block in test_blocks:
            if any(block["line_start"] <= line <= block["line_end"] for line in file_changes):
                names.add(block["name"])
        parameterized_by_suite: Dict[str, Set[str]] = {}
        for block in test_blocks:
            if block.get("macro") == "TEST_P":
                parameterized_by_suite.setdefault(block["suite"], set()).add(block["name"])
        for block in gtest_instantiation_blocks(source):
            if any(block["line_start"] <= line <= block["line_end"] for line in file_changes):
                names.update(parameterized_by_suite.get(block["suite"], set()))
    return names


def _case_matches(candidate: str, wanted: str) -> bool:
    if candidate == wanted:
        return True
    # Parameterized GoogleTest names may add a prefix and/or numeric suffix.
    return candidate.endswith("/" + wanted) or candidate.startswith(wanted + "/") or f"/{wanted}/" in candidate


def _case_suite(case_name: str) -> str:
    suite = str(case_name or "").split(".", 1)[0]
    parts = [part for part in suite.split("/") if part]
    while parts and parts[-1].isdigit():
        parts.pop()
    return parts[-1] if parts else suite


def order_specs_with_regressions_first(
    specs: Sequence[TestSpec], regression_names: Set[str]
) -> Tuple[List[TestSpec], List[TestSpec]]:
    """Order exact regressions, their suites, then all remaining cases."""
    regressions = [
        spec for spec in specs
        if spec.gtest_filter and any(
            _case_matches(spec.gtest_filter, wanted) for wanted in regression_names
        )
    ]
    regression_ids = {spec.test_id for spec in regressions}
    regression_suites = {_case_suite(name) for name in regression_names}
    same_suite = [
        spec for spec in specs
        if spec.test_id not in regression_ids
        and spec.gtest_filter
        and _case_suite(spec.gtest_filter) in regression_suites
    ]
    prioritized_ids = regression_ids | {spec.test_id for spec in same_suite}
    remaining = [spec for spec in specs if spec.test_id not in prioritized_ids]
    return regressions + same_suite + remaining, regressions


def select_specs(
    repo: Path,
    bug: BugEntry,
    all_ctest_names: Sequence[str],
    *,
    scope: str,
    max_tests: int,
) -> Tuple[List[TestSpec], dict]:
    target_ctest_names: List[str] = []
    for requested in target_names(bug):
        pattern = re.compile("^" + re.escape(requested).replace(r"\*", ".*") + "$")
        for ctest_name in all_ctest_names:
            if pattern.match(ctest_name) and ctest_name not in target_ctest_names:
                target_ctest_names.append(ctest_name)
    ctest_names = list(all_ctest_names) if scope == "all" else target_ctest_names
    specs = base.discover_test_specs(repo / BUILD_DIR_NAME, ctest_names)
    changed_cases = regression_case_names(repo, bug)
    ordered, regression_specs = order_specs_with_regressions_first(specs, changed_cases)
    detail = {
        "requested_scope": scope,
        "effective_scope": scope,
        "regression_cases": sorted(changed_cases),
        "matched_regression_tests": len(regression_specs),
        "candidate_tests": len(specs),
        "max_tests": max_tests,
        "selection_policy": "regression_cases_first_then_same_suite_then_fill_to_max_tests",
    }
    if scope == "regression":
        if regression_specs:
            ordered = regression_specs
        else:
            detail["effective_scope"] = "target"
            detail["scope_fallback"] = "no_changed_gtest_case_matched"
    selected = ordered[:max_tests] if max_tests > 0 else ordered
    detail["selection_truncated"] = len(selected) < len(ordered)
    regression_ids = {item.test_id for item in regression_specs}
    detail["selected_regression_tests"] = sum(
        spec.test_id in regression_ids for spec in selected
    )
    return selected, detail


def _is_production_source(rel_path: str) -> bool:
    rel = rel_path.replace("\\", "/").lstrip("./")
    if not rel.endswith((".h", ".hpp", ".hh", ".c", ".cc", ".cpp", ".cxx")):
        return False
    return rel.startswith("source/") or rel.startswith("include/spirv-tools/")


def filter_production_coverage(cov_map: Dict[str, List[str]]) -> Dict[str, List[str]]:
    return {rel: funcs for rel, funcs in cov_map.items() if _is_production_source(rel)}


def _normalize_cpp_function(name: str) -> str:
    value = re.sub(r"\s+", " ", str(name or "")).strip()
    value = base._strip_cpp_parameter_list(value)
    value = re.sub(r"^(?:virtual|static|constexpr|const|inline|typename)\s+", "", value)
    value = base._drop_cpp_return_type(value)
    value = base._strip_cpp_template_args(value)
    return value.strip()


base._is_production_source = _is_production_source
base.filter_production_coverage = filter_production_coverage
base._normalize_cpp_function = _normalize_cpp_function


def _compile_cmd(repo: Path, jobs: int, targets: Sequence[str]) -> str:
    target_text = " ".join(shlex.quote(item) for item in ninja_target_names(targets))
    launcher = (
        "-DCMAKE_C_COMPILER_LAUNCHER=ccache "
        "-DCMAKE_CXX_COMPILER_LAUNCHER=ccache "
        if shutil.which("ccache") else ""
    )
    return (
        f"cd {shlex.quote(str(repo))} && cmake -G Ninja -S . -B {BUILD_DIR_NAME} "
        f"-DCMAKE_BUILD_TYPE=Debug -DCMAKE_EXPORT_COMPILE_COMMANDS=ON "
        f"-DSPIRV_WERROR=OFF -DSPIRV_SKIP_TESTS=OFF -DEFFCEE_BUILD_TESTING=OFF "
        f"{launcher}"
        f"-DCMAKE_CXX_FLAGS='{COV_CFLAGS}' && "
        f"ninja -C {BUILD_DIR_NAME} -j{jobs} {target_text}"
    )


