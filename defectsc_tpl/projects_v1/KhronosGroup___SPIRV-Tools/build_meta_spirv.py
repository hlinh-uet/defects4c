def _rebind_specs(build_dir: Path, selected: Sequence[TestSpec]) -> List[TestSpec]:
    entries = {entry.name: entry for entry in base.list_ctest_entries(build_dir)}
    rebound: List[TestSpec] = []
    for spec in selected:
        entry = entries.get(spec.ctest_name, CTestEntry(spec.ctest_name))
        rebound.append(TestSpec(
            test_id=spec.test_id,
            ctest_name=spec.ctest_name,
            command=entry.command,
            working_directory=entry.working_directory,
            gtest_filter=spec.gtest_filter,
        ))
    return rebound


def _run_outcomes(build_dir: Path, specs: Sequence[TestSpec], timeout: int, label: str) -> Tuple[List[TestResult], Dict[str, str]]:
    rows: List[TestResult] = []
    outcomes: Dict[str, str] = {}
    for index, spec in enumerate(specs, 1):
        passed, output = base.run_one_test_spec(build_dir, spec, timeout=timeout, asan=False)
        outcome = "PASS" if passed else "FAIL"
        outcomes[spec.test_id] = outcome
        rows.append(TestResult(
            test_id=spec.test_id,
            outcome=outcome,
            fail_reason="" if passed else output[-3000:],
            actual_output="" if passed else output[-3000:],
        ))
        if index % 25 == 0 or index == len(specs):
            failures = sum(1 for value in outcomes.values() if value == "FAIL")
            log(f"  [{label}] {index}/{len(specs)} (fail={failures})")
    return rows, outcomes


def process_bug(
    bug: BugEntry,
    out_root: Path,
    metadata_dir: Path,
    raw_dir: Path,
    *,
    jobs: int,
    test_timeout: int,
    skip_if_exists: bool,
    clone_if_missing: bool,
    skip_coverage: bool,
    dual_run: bool,
    test_scope: str,
    max_tests: int,
) -> Optional[Path]:
    filename = f"{bug.safe_bug_id}_meta.json"
    metadata_path = metadata_dir / filename
    raw_path = raw_dir / filename
    if skip_if_exists and metadata_path.is_file():
        try:
            existing = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            existing = {}
        existing_phase = existing.get("phase_info") if isinstance(existing, dict) else {}
        current = (
            isinstance(existing_phase, dict)
            and existing.get("project") == PROJECT_NAME
            and existing_phase.get("test_granularity") == "gtest_case"
            and int(existing_phase.get("pipeline_version") or 0) == METADATA_PIPELINE_VERSION
            and existing_phase.get("requested_scope") == test_scope
            and int(existing_phase.get("max_tests") or 0) == int(max_tests)
            and bool(existing_phase.get("dual_run")) == bool(dual_run)
            and bool(existing_phase.get("skip_coverage")) == bool(skip_coverage)
            and not existing_phase.get("errors")
            and bool(existing.get("tests"))
        )
        if current:
            log(f"[skip] {bug.bug_id}")
            return metadata_path
        log(f"[rerun] {bug.bug_id} existing metadata does not match requested pipeline options")

    log(f"=== {bug.bug_id} | {bug.type_name or ''} ===")
    try:
        repo = base.ensure_repo(out_root, bug.sha_after, clone_if_missing=clone_if_missing)
    except Exception as exc:
        log(f"  [error] repo: {exc}")
        return None

    targets = target_names(bug)
    compile_cmd = _compile_cmd(repo, jobs, targets)
    source_file = str(repo / bug.src_files[0]) if bug.src_files else ""
    test_cmd_template = f"bash {shlex.quote(str(repo / 'run_one_test.sh'))} {{test_id}}"
    phase_info = {
        "pipeline_version": METADATA_PIPELINE_VERSION,
        "dual_run": dual_run,
        "skip_coverage": skip_coverage,
        "test_granularity": "gtest_case",
        "build_targets": targets,
        "max_tests": max_tests,
        "selection_policy": "regression_cases_first_then_same_suite_then_fill_to_max_tests",
        "errors": [],
    }

    try:
        base.checkout_buggy(repo, bug)
        if not compile_project(
            repo, jobs=jobs, coverage=False, targets=targets,
            build_all=test_scope == "all",
        ):
            record = _empty_record(bug, repo, compile_cmd, "buggy_phase_a_compile_failed")
            base._write_meta(raw_path, record)
            base._write_meta(metadata_path, record)
            return None
        base.write_run_one_test(repo)
        build_dir = repo / BUILD_DIR_NAME
        all_ctest_names = base.list_ctest_tests(build_dir)
        selected, scope_info = select_specs(
            repo,
            bug,
            all_ctest_names,
            scope=test_scope,
            max_tests=max_tests,
        )
    except Exception as exc:
        log(f"  [error] discovery: {exc}")
        record = _empty_record(bug, repo, compile_cmd, f"discovery_failed:{exc}")
        base._write_meta(raw_path, record)
        base._write_meta(metadata_path, record)
        return None

    phase_info.update(scope_info)
    phase_info["all_ctest_tests"] = len(all_ctest_names)
    phase_info["selected_ctest_tests"] = len({spec.ctest_name for spec in selected})
    phase_info["all_tests"] = scope_info.get("candidate_tests")
    phase_info["selected_tests"] = len(selected)
    if not selected:
        phase_info["errors"].append("no_tests_selected")
    log(
        f"  [tests] ctest={len(all_ctest_names)}, selected_cases={len(selected)}, "
        f"scope={phase_info.get('effective_scope')}"
    )

    results, _ = _run_outcomes(build_dir, selected, test_timeout, "phaseA-buggy")
    fixed_map: Dict[str, str] = {}
    if dual_run:
        try:
            base.checkout_fixed(repo, bug)
            if compile_project(
                repo, jobs=jobs, coverage=False, targets=targets,
                build_all=test_scope == "all",
            ):
                _, fixed_map = _run_outcomes(
                    repo / BUILD_DIR_NAME,
                    _rebind_specs(repo / BUILD_DIR_NAME, selected),
                    test_timeout,
                    "phaseA-fixed",
                )
            else:
                phase_info["errors"].append("fixed_phase_a_compile_failed")
        except Exception as exc:
            phase_info["errors"].append(f"fixed_phase_exception:{exc}")

    raw_cov: Dict[str, List[str]] = {}
    meta_cov: Dict[str, List[str]] = {}
    cov_errors: Dict[str, str] = {}
    if not skip_coverage:
        try:
            base.checkout_buggy(repo, bug)
            if compile_project(
                repo, jobs=jobs, coverage=True, targets=targets,
                build_all=test_scope == "all",
            ):
                cov_dir = repo / BUILD_DIR_NAME
                cov_specs = _rebind_specs(cov_dir, selected)
                for index, spec in enumerate(cov_specs, 1):
                    base.clear_gcda(cov_dir)
                    base.run_one_test_spec(cov_dir, spec, timeout=test_timeout, asan=False)
                    coverage, error = base.collect_coverage(repo, cov_dir, verbose=index <= 2)
                    raw_cov[spec.test_id] = base.coverage_to_qualified(coverage)
                    meta_cov[spec.test_id] = base.coverage_to_qualified(filter_production_coverage(coverage))
                    cov_errors[spec.test_id] = error
                    if index % 25 == 0 or index == len(cov_specs):
                        log(f"  [phaseB] {index}/{len(cov_specs)}")
            else:
                phase_info["errors"].append("coverage_compile_failed")
                cov_errors.update({spec.test_id: "coverage_compile_failed" for spec in selected})
        except Exception as exc:
            phase_info["errors"].append(f"coverage_phase_exception:{exc}")
            cov_errors.update({spec.test_id: f"coverage_phase_exception:{exc}" for spec in selected})

    raw_results: List[TestResult] = []
    metadata_results: List[TestResult] = []
    for result in results:
        common = dict(
            test_id=result.test_id,
            outcome=result.outcome,
            outcome_fixed=fixed_map.get(result.test_id, "NOT_RUN"),
            fail_reason=result.fail_reason,
            actual_output=result.actual_output,
            coverage_error=cov_errors.get(result.test_id, ""),
        )
        raw_results.append(TestResult(**common, covered_functions=raw_cov.get(result.test_id, [])))
        metadata_results.append(TestResult(**common, covered_functions=meta_cov.get(result.test_id, [])))

    base.write_run_one_test(repo)
    ground_truth = base.extract_ground_truth(bug, repo)
    common_record = {
        "bug_id": bug.bug_id,
        "dataset_name": "defects4c",
        "language": "C++",
        "project": PROJECT_NAME,
        "commit_after": bug.sha_after,
        "commit_before": bug.sha_before,
        "source_file": source_file,
        "source_basename": os.path.basename(source_file) if source_file else "",
        "test_files": bug.test_files,
        "compile_cmd": compile_cmd,
        "test_cmd_template": test_cmd_template,
        "type_name": bug.type_name,
        "ground_truth_functions": ground_truth,
        "ground_truth": [f"{source_file}::{name}" for name in ground_truth] if source_file else [],
    }
    raw_record = {
        **common_record,
        "phase_info": {**phase_info, "coverage_scope": "full_gcov"},
        "tests": [base._test_to_dict(row) for row in raw_results],
    }
    metadata_record = {
        **common_record,
        "phase_info": {
            **phase_info,
            "coverage_scope": "production_source_only",
            "coverage_filter": "keep source/* and include/spirv-tools/*",
        },
        "tests": [base._test_to_dict(row) for row in metadata_results],
    }
    base._write_meta(raw_path, raw_record)
    base._write_meta(metadata_path, metadata_record)
    log(f"  [ok] wrote {metadata_path}")
    return None if phase_info["errors"] else metadata_path


def copy_bug_catalog(metadata_dir: Path) -> None:
    destination = metadata_dir / BUGS_JSON.name
    if not destination.is_file() or destination.read_bytes() != BUGS_JSON.read_bytes():
        shutil.copy2(BUGS_JSON, destination)


def check_required_tools() -> bool:
    missing = [name for name in ("git", "cmake", "ninja", "ctest", "gcc", "g++", "gcov") if not shutil.which(name)]
    if missing:
        log(f"[error] missing required tools: {', '.join(missing)}")
        return False
    return True


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Build Unified-Debugging metadata for SPIRV-Tools.")
    parser.add_argument("--sha", action="append", default=[])
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--out-root", type=Path, default=default_out_root())
    parser.add_argument("--metadata-dir", type=Path, default=default_metadata_dir())
    parser.add_argument("--raw-dir", type=Path, default=default_raw_dir())
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--test-timeout", type=int, default=180)
    parser.add_argument("--test-scope", choices=("regression", "target", "all"), default="target")
    parser.add_argument(
        "--max-tests",
        type=int,
        default=200,
        help="Maximum cases after regression-first ordering. Use 0 for unlimited.",
    )
    parser.add_argument("--skip-coverage", action="store_true")
    parser.add_argument("--dual-run", dest="dual_run", action="store_true", default=True)
    parser.add_argument("--single-run", dest="dual_run", action="store_false")
    parser.add_argument("--skip-if-exists", action="store_true")
    parser.add_argument("--clone", action="store_true")
    parser.add_argument("--include-manual-status-2", action="store_true")
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args(argv)

    bugs = base.load_bugs()
    if not args.include_manual_status_2:
        bugs = [bug for bug in bugs if int(bug.raw.get("status_manual") or 0) == 1]
    if args.sha:
        wanted = tuple(item for item in args.sha if item)
        bugs = [bug for bug in bugs if bug.sha_after in wanted or bug.sha_after.startswith(wanted)]
    if args.limit:
        bugs = bugs[:args.limit]
    if args.list:
        for bug in bugs:
            print(f"{bug.sha_after}\t{bug.bug_id}\t{','.join(bug.test_files)}")
        return 0
    if not bugs:
        log("No matching bugs.")
        return 1
    if not check_required_tools():
        return 4

    args.metadata_dir.mkdir(parents=True, exist_ok=True)
    args.raw_dir.mkdir(parents=True, exist_ok=True)
    copy_bug_catalog(args.metadata_dir)
    log(
        f"Will process {len(bugs)} bug(s), scope={args.test_scope}, "
        f"max_tests={max(0, args.max_tests)}, jobs={max(1, args.jobs)}."
    )

    try:
        lock = acquire_lock(args.out_root)
    except RuntimeError as exc:
        log(f"[error] {exc}")
        return 3
    failures = 0
    try:
        for bug in bugs:
            try:
                result = process_bug(
                    bug,
                    args.out_root,
                    args.metadata_dir,
                    args.raw_dir,
                    jobs=max(1, args.jobs),
                    test_timeout=max(1, args.test_timeout),
                    skip_if_exists=args.skip_if_exists,
                    clone_if_missing=args.clone,
                    skip_coverage=args.skip_coverage,
                    dual_run=args.dual_run,
                    test_scope=args.test_scope,
                    max_tests=max(0, args.max_tests),
                )
                if result is None:
                    failures += 1
            except KeyboardInterrupt:
                return 130
            except Exception as exc:
                failures += 1
                log(f"  [exception] {bug.bug_id}: {exc}")
    finally:
        fcntl.flock(lock.fileno(), fcntl.LOCK_UN)
        lock.close()
    log(f"DONE. fail={failures}/{len(bugs)}")
    return 0 if failures == 0 else 2


if __name__ == "__main__":
    raise SystemExit(main())
